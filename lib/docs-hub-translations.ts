export function resolveDocsLanguage(candidate: unknown): DocsLanguage {
  if (typeof candidate !== "string") return "en";
  return DOCS_LANGUAGE_OPTIONS.find((option) => option.code === candidate)?.code ?? "en";
}

export function translateDocsText(language: DocsLanguage, english: string): string {
  return translations[language]?.[english] ?? english;
}
